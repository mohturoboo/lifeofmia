export type DictionaryKey = keyof typeof fr;

/**
 * Categories de pluriel du CLDR.
 *
 * Le francais n'en distingue que deux — singulier et pluriel — la ou l'arabe
 * en compte six. Le dictionnaire de reference ne peut donc pas imposer sa
 * grammaire aux autres langues : il fixe les cles, chaque langue fournit les
 * FORMES dont elle a besoin.
 */
type FormePlurielle = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other';

/** Racines des cles a pluriel, deduites de celles qui portent `_one`. */
type RacinePluriel = Extract<DictionaryKey, `${string}_one`> extends `${infer Racine}_one`
  ? Racine
  : never;

/**
 * Un dictionnaire fournit TOUTES les cles du francais, et peut y ajouter les
 * formes plurielles supplementaires de sa propre grammaire — mais uniquement
 * celles-la : une cle inventee reste une erreur de compilation.
 */
export type Dictionary = Record<DictionaryKey, string> &
  Partial<Record<`${RacinePluriel}_${FormePlurielle}`, string>>;
